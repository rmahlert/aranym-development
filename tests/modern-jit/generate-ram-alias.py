#!/usr/bin/env python3
"""Emit real MOVE probes, independently checked by the guest RAM/state oracle."""
from pathlib import Path
R=Path(__file__).resolve().parent/'guest'
cases=[]
for size in [1,2,4]:
    for src in [2,3,4,5]:
        for dst in [2,3,4,5]:
            for alias in [0,1]:cases.append((size,src,dst,alias,0))
        cases.append((size,src,0,0,1)) # memory to D0
        if size!=1:
            for alias in [0,1]:cases.append((size,src,1,alias,2)) # MOVEA
def ea(mode,reg,disp):return {2:f'(%a{reg})',3:f'(%a{reg})+',4:f'-(%a{reg})',5:f'{disp}(%a{reg})'}[mode]
assembly=['/* Generated by generate-ram-alias.py; GPL-2.0-or-later. */','.text','.even','.globl _ram_alias_begin,_ram_alias_end','_ram_alias_begin:',
'''.macro probe name,insn
.globl \\name
\\name:
 movem.l %d2-%d7/%a2-%a6,-(%sp)
 move.l %sp,_ram_alias_sp
 movem.l _ram_alias_input,%d0-%d7/%a0-%a6
 move.w _ram_alias_ccr,%ccr
 \\insn
 move.w %ccr,_ram_alias_reply
 movem.l %d0-%d7/%a0-%a7,_ram_alias_output
 movem.l (%sp)+,%d2-%d7/%a2-%a6
 rts
.endm''']
header=['/* Generated probe inventory; GPL-2.0-or-later. */','struct RamCase {unsigned size,src,dst,alias,kind,index;void (*fn)(void);};']
for i,(size,src,dst,alias,kind) in enumerate(cases):
    op='movea' if kind==2 else 'move'; suffix={1:'b',2:'w',4:'l'}[size]
    destination=ea(dst,2 if alias else 3,-5) if kind==0 else '%d0' if kind==1 else '%a2' if alias else '%a3'
    assembly.append(f'probe _ram_alias_{i},"{op}.{suffix} {ea(src,2,3)},{destination}"')
    header.append(f'extern void ram_alias_{i}(void);')
header.append('static const struct RamCase cases[]={')
for i,(size,src,dst,alias,kind) in enumerate(cases):
    ordinal={1:0,2:1,4:2}[size];index=ordinal if kind==1 else 5+ordinal if kind==2 else 3+ordinal
    header.append(f'{{{size},{src},{dst},{alias},{kind},{index},ram_alias_{i}}},')
header.append('};');assembly.append('_ram_alias_end:')
(R/'ram-alias-probes.S').write_text('\n'.join(assembly)+'\n')
(R/'ram-alias-probes.h').write_text('\n'.join(header)+'\n')
print(len(cases),'real RAM MOVE/update/alias probe forms')
